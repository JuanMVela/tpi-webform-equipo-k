-- 1. SEGURIDAD Y USUARIOS

CREATE TABLE PERFILES (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(50) NOT NULL,
    CONSTRAINT PK_PERFILES PRIMARY KEY (Id),
    CONSTRAINT UQ_PERFILES_Nombre UNIQUE (Nombre)
);
GO

CREATE TABLE USUARIOS (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Apellido VARCHAR(100) NOT NULL,
    Email VARCHAR(150) NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL,
    Telefono VARCHAR(30) NULL,
    IdPerfil INT NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (Id),
    CONSTRAINT UQ_USUARIOS_Email UNIQUE (Email),
    CONSTRAINT FK_USUARIOS_PERFILES FOREIGN KEY (IdPerfil)
        REFERENCES PERFILES(Id)
);
GO

CREATE TABLE DIRECCIONES (
    Id INT IDENTITY(1,1) NOT NULL,
    IdUsuario INT NOT NULL,
    Calle VARCHAR(150) NOT NULL,
    Numero VARCHAR(20) NOT NULL,
    Localidad VARCHAR(100) NOT NULL,
    CodigoPostal VARCHAR(20) NOT NULL,
    Observaciones VARCHAR(300) NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_DIRECCIONES PRIMARY KEY (Id),
    CONSTRAINT FK_DIRECCIONES_USUARIOS FOREIGN KEY (IdUsuario)
        REFERENCES USUARIOS(Id)
);
GO

-- 2. CATALOGO

CREATE TABLE CATEGORIAS (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (Id),
    CONSTRAINT UQ_CATEGORIAS_Nombre UNIQUE (Nombre)
);
GO

CREATE TABLE MARCAS (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_MARCAS PRIMARY KEY (Id),
    CONSTRAINT UQ_MARCAS_Nombre UNIQUE (Nombre)
);
GO

CREATE TABLE PRODUCTOS (
    Id INT IDENTITY(1,1) NOT NULL,
    Codigo VARCHAR(50) NOT NULL,
    Nombre VARCHAR(150) NOT NULL,
    Descripcion VARCHAR(500) NULL,
    Precio DECIMAL(18,2) NOT NULL,
    Stock INT NOT NULL,
    IdCategoria INT NOT NULL,
    IdMarca INT NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (Id),
    CONSTRAINT UQ_PRODUCTOS_Codigo UNIQUE (Codigo),
    CONSTRAINT FK_PRODUCTOS_CATEGORIAS FOREIGN KEY (IdCategoria)
        REFERENCES CATEGORIAS(Id),
    CONSTRAINT FK_PRODUCTOS_MARCAS FOREIGN KEY (IdMarca)
        REFERENCES MARCAS(Id)
);
GO

CREATE TABLE IMAGENES (
    Id INT IDENTITY(1,1) NOT NULL,
    IdProducto INT NOT NULL,
    ImagenUrl VARCHAR(1000) NOT NULL,
    EsPrincipal BIT NOT NULL,
    Orden INT NOT NULL,
    CONSTRAINT PK_IMAGENES PRIMARY KEY (Id),
    CONSTRAINT FK_IMAGENES_PRODUCTOS FOREIGN KEY (IdProducto)
        REFERENCES PRODUCTOS(Id)
);
GO

-- 3. CONFIGURACION DEL ECOMMERCE

CREATE TABLE FORMAS_PAGO (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_FORMAS_PAGO PRIMARY KEY (Id),
    CONSTRAINT UQ_FORMAS_PAGO_Nombre UNIQUE (Nombre)
);
GO

CREATE TABLE FORMAS_ENTREGA (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    RequiereDireccion BIT NOT NULL,
    Activo BIT NOT NULL,
    CONSTRAINT PK_FORMAS_ENTREGA PRIMARY KEY (Id),
    CONSTRAINT UQ_FORMAS_ENTREGA_Nombre UNIQUE (Nombre)
);
GO

CREATE TABLE ESTADOS_PEDIDO (
    Id INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(50) NOT NULL,
    CONSTRAINT PK_ESTADOS_PEDIDO PRIMARY KEY (Id),
    CONSTRAINT UQ_ESTADOS_PEDIDO_Nombre UNIQUE (Nombre)
);
GO

-- 4. PEDIDOS Y VENTAS

CREATE TABLE PEDIDOS (
    Id INT IDENTITY(1,1) NOT NULL,
    IdCliente INT NOT NULL,
    Fecha DATETIME NOT NULL,
    Total DECIMAL(18,2) NOT NULL,
    IdFormaPago INT NOT NULL,
    IdFormaEntrega INT NOT NULL,
    IdDireccion INT NULL,
    IdEstado INT NOT NULL,
    ObservacionesInternas NVARCHAR(1000) NULL,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (Id),
    CONSTRAINT FK_PEDIDOS_USUARIOS FOREIGN KEY (IdCliente)
        REFERENCES USUARIOS(Id),
    CONSTRAINT FK_PEDIDOS_FORMAS_PAGO FOREIGN KEY (IdFormaPago)
        REFERENCES FORMAS_PAGO(Id),
    CONSTRAINT FK_PEDIDOS_FORMAS_ENTREGA FOREIGN KEY (IdFormaEntrega)
        REFERENCES FORMAS_ENTREGA(Id),
    CONSTRAINT FK_PEDIDOS_DIRECCIONES FOREIGN KEY (IdDireccion)
        REFERENCES DIRECCIONES(Id),
    CONSTRAINT FK_PEDIDOS_ESTADOS_PEDIDO FOREIGN KEY (IdEstado)
        REFERENCES ESTADOS_PEDIDO(Id)
);
GO

CREATE TABLE DETALLE_PEDIDO (
    IdPedido INT NOT NULL,
    IdProducto INT NOT NULL,
    Cantidad INT NOT NULL,
    PrecioUnitario DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_DETALLE_PEDIDO PRIMARY KEY (IdPedido, IdProducto),
    CONSTRAINT FK_DETALLE_PEDIDO_PEDIDOS FOREIGN KEY (IdPedido)
        REFERENCES PEDIDOS(Id),
    CONSTRAINT FK_DETALLE_PEDIDO_PRODUCTOS FOREIGN KEY (IdProducto)
        REFERENCES PRODUCTOS(Id)
);
GO

CREATE TABLE OBSERVACIONES_PEDIDO (
    Id INT IDENTITY(1,1) NOT NULL,
    IdPedido INT NOT NULL,
    IdUsuario INT NOT NULL,
    Fecha DATETIME NOT NULL,
    Observacion VARCHAR(500) NOT NULL,
    CONSTRAINT PK_OBSERVACIONES_PEDIDO PRIMARY KEY (Id),
    CONSTRAINT FK_OBSERVACIONES_PEDIDO_PEDIDOS FOREIGN KEY (IdPedido)
        REFERENCES PEDIDOS(Id),
    CONSTRAINT FK_OBSERVACIONES_PEDIDO_USUARIOS FOREIGN KEY (IdUsuario)
        REFERENCES USUARIOS(Id)
);
GO

-- 5. COMPROBANTES DE PAGO
CREATE TABLE COMPROBANTES_PAGO (
    Id INT IDENTITY(1,1) NOT NULL,
    IdPedido INT NOT NULL,
    NombreArchivo NVARCHAR(255) NOT NULL,
    TipoContenido VARCHAR(50) NOT NULL,
    Archivo VARBINARY(MAX) NOT NULL,
    FechaCarga DATETIME NOT NULL DEFAULT GETDATE(),
    Estado VARCHAR(20) NOT NULL DEFAULT 'En revision',
    CONSTRAINT PK_COMPROBANTES_PAGO PRIMARY KEY (Id),
    CONSTRAINT FK_COMPROBANTES_PAGO_PEDIDOS FOREIGN KEY (IdPedido)
        REFERENCES PEDIDOS(Id),
    CONSTRAINT CK_COMPROBANTES_PAGO_ESTADO
        CHECK (Estado IN ('En revision', 'Aprobado', 'Rechazado'))
);
GO

